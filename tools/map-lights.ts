// Light sources of the original maps (lamps, campfires, glowing scenery) → src/world/map-lights.ts: numbers only —
// floor, hex, light radius (in hexes) and intensity (in percent).
// Run: node tools/map-lights.ts — takes all original maps our levels are made from (the `original` field).
// The game converts the hex to a level cell by the level's frame (`hexFrame`) and draws a pool of light around it.
// Added a level from a new map — run again.
import fs from 'node:fs';
import { createRequire } from 'node:module';
import { createProtoTypes, parseMap } from '../src/formats/map.ts';
import { OBJ_TYPE, idType } from '../src/formats/pro.ts';
import { LEVELS } from '../src/world/levels/index.ts';

const require = createRequire(import.meta.url);
const { openGame } = require('../electron/gamefiles.cjs');

const config = JSON.parse(fs.readFileSync('.local/config.json', 'utf8'));
const game = openGame(config.gameDir);
const B = String.fromCharCode(92);
const read = (name: string): Uint8Array | null => game.read(name);
const types = createProtoTypes(read);

/** Full light intensity in the original. */
const FULL = 65536;

const maps = [...new Set(Object.values(LEVELS).map((def) => (def.original ?? '').toUpperCase()))].filter((m) => m && read(`MAPS${B}${m}.MAP`)).sort();
const lines: string[] = [];
let total = 0;
for (const name of maps) {
  const map = parseMap(read(`MAPS${B}${name}.MAP`)!, types);
  const lights: string[] = [];
  map.objects.forEach((list, elevation) => {
    for (const o of list) {
      // Critter light (in the original only the hero has it) is skipped: light sources are scenery and items on the floor.
      if (idType(o.pid) === OBJ_TYPE.critter || o.lightDistance <= 0 || o.lightIntensity <= 0 || o.tile < 0) continue;
      lights.push(`[${elevation}, ${o.tile}, ${o.lightDistance}, ${Math.round((Math.min(FULL, o.lightIntensity) / FULL) * 100)}]`);
    }
  });
  if (lights.length === 0) continue;
  total += lights.length;
  lines.push(`  ${name}: [${lights.join(', ')}],`);
}
game.close();

const out = `// Generated by tools/map-lights.ts — do not edit by hand, run it again. Light sources of the original maps:
// [floor, hex, light radius in hexes, intensity in percent]. No texts or pictures of the original are here.

export const MAP_LIGHTS: Record<string, [number, number, number, number][]> = {
${lines.join('\n')}
};
`;
fs.writeFileSync('src/world/map-lights.ts', out);
console.log(`Wrote src/world/map-lights.ts: ${lines.length} maps, ${total} light sources`);
