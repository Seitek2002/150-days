// ---------- setup ----------

function findGameDir(): string {
  const fromArgs = process.argv[2];
  if (fromArgs) return fromArgs;
  try {
    return JSON.parse(fs.readFileSync(path.join(root, '.local', 'config.json'), 'utf8')).gameDir ?? '';
  } catch {
    return '';
  }
}

const gameDir = findGameDir();
if (!gameDir || !checkGameFolder(gameDir).ok) {
  console.error('Fallout 1 copy not found. Specify the folder: node tools/dump-data.ts "<folder with master.dat>"');
  process.exit(1);
}
const game = openGame(gameDir);
const read = (name: string): Uint8Array => {
  const data = game.read(name);
  if (!data) throw new Error('File missing from the game copy: ' + name);
  return data;
};

