// Map transitions in the scripts of the player's copy: node tools/load-map-calls.ts
// Writes docs/data/load-map.md (on this computer only) and prints a short summary. Two tables:
//  1. who calls `load_map` — script, procedure, map (file name or number in the original's map list) and entrance number;
//  2. start cells of maps by entrance number: the map script in `map_enter_p_proc` checks global variable 32 (it equals the entrance
//     number from `load_map`) and calls `override_map_start(x, y, elevation, rotation)`; hex cell = y × 200 + x. No condition — the default cell.
import fs from 'node:fs';
import { createRequire } from 'node:module';
import { createProtoTypes, parseMap } from '../src/formats/map.ts';
import { parseLst } from '../src/formats/text.ts';
import { IntProgram } from '../src/script/int.ts';
import { listing } from '../src/script/disasm.ts';

const require = createRequire(import.meta.url);
const { openGame } = require('../electron/gamefiles.cjs');
const config = JSON.parse(fs.readFileSync('.local/config.json', 'utf8'));
const game = openGame(config.gameDir);
const B = String.fromCharCode(92);
const read = (n: string) => game.read(n);
const types = createProtoTypes(read);

/** The original's map numbers in order (`load_map` and exits between maps use the number). */
const MAPS = 'DESERT1 DESERT2 DESERT3 HALLDED HOTEL WATRSHD VAULT13 VAULTENT VAULTBUR VAULTNEC JUNKENT JUNKCSNO JUNKKILL BROHDENT BROHD12 BROHD34 CAVES CHILDRN1 CHILDRN2 CITY1 COAST1 COAST2 COLATRUK FSAUSER RAIDERS SHADYE SHADYW GLOWENT LAADYTUM LAFOLLWR MBENT MBSTRG12 MBVATS12 MSTRLR12 MSTRLR34 V13ENT HUBENT DETHCLAW HUBDWNTN HUBHEIGT HUBOLDTN HUBWATER GLOW1 GLOW2 LABLADES LARIPPER LAGUNRUN CHILDEAD MBDEAD MOUNTN1 MOUNTN2 FOOT TARDIS TALKCOW USEDCAR BRODEAD DESCRVN1 DESCRVN2 MNTCRVN1 MNTCRVN2 VIPERS DESCRVN3 MNTCRVN3 DESCRVN4 MNTCRVN4 HUBMIS1'.split(' ');
const names = parseLst(read(`SCRIPTS${B}SCRIPTS.LST`)!).map((l: string) => l.split('.')[0]!.trim().toUpperCase());

const rows = (text: string): string[] => text.split('\n');
const pushOf = (line: string) => /^\s*\d+\s+push (.+)$/.exec(line)?.[1];
const listingOf = (name: string): string[] | null => {
  const bytes = read(`SCRIPTS${B}${name}.INT`);
  if (!bytes) return null;
  try {
    return rows(listing(new IntProgram(name, bytes)));
  } catch {
    return null;
  }
};

// ---- 1. load_map calls ----
const calls: string[] = [];
for (const name of new Set(names)) {
  const lines = listingOf(name);
  if (!lines) continue;
  lines.forEach((line, i) => {
    if (!/\bload_map\b/.test(line)) return;
    const pushes: string[] = [];
    for (let j = i - 1; j >= 0 && pushes.length < 2; j--) {
      const p = pushOf(lines[j]!);
      if (p !== undefined) pushes.unshift(p);
    }
    let proc = '';
    for (let j = i; j >= 0; j--) {
      if (/^[A-Za-z_0-9]+:/.test(lines[j]!)) {
        proc = lines[j]!.trim().replace(/:.*$/, '');
        break;
      }
    }
    const map = pushes[0] ?? '?';
    const label = /^\d+$/.test(map) ? `${map} (${MAPS[Number(map)] ?? '?'})` : map.replace(/"/g, '');
    calls.push(`| ${name} | ${proc || '—'} | ${label} | ${pushes[1] ?? '?'} |`);
  });
}

// ---- 2. start cells by entrance number ----
const starts: string[] = [];
for (const map of MAPS) {
  const bytes = read(`MAPS${B}${map}.MAP`);
  if (!bytes) continue;
  let script: string | undefined;
  try {
    const m = parseMap(bytes, types);
    script = m.header.scriptIndex > 0 ? names[m.header.scriptIndex - 1] : undefined;
    starts.push(`<!-- ${map}: header entrance cell ${m.header.enteringTile}, elevation ${m.header.enteringElevation} -->`);
  } catch {
    continue;
  }
  if (!script) continue;
  const lines = listingOf(script);
  if (!lines) continue;
  const from = lines.findIndex((l) => /^map_enter_p_proc:/.test(l));
  if (from < 0) continue;
  let to = lines.findIndex((l, i) => i > from && /^[A-Za-z_0-9]+:/.test(l));
  if (to < 0) to = lines.length;
  let entrance = 'default';
  for (let i = from; i < to; i++) {
    // condition "global_var(32) == N": push 32, global_var, push N, equal
    if (/\bglobal_var\b/.test(lines[i]!) && pushOf(lines[i - 1]!) === '32' && /\bequal\b/.test(lines[i + 2] ?? '') && pushOf(lines[i + 1]!) !== undefined) entrance = pushOf(lines[i + 1]!)!;
    if (/\boverride_map_start\b/.test(lines[i]!)) {
      const v: number[] = [];
      for (let j = i - 1; j >= from && v.length < 4; j--) {
        const p = pushOf(lines[j]!);
        if (p !== undefined && /^-?\d+$/.test(p)) v.unshift(Number(p));
      }
      if (v.length === 4) starts.push(`| ${map} | ${script} | ${entrance} | ${v[1]! * 200 + v[0]!} | ${v[2]} | ${v[3]} |`);
      entrance = 'default';
    }
  }
}

const out = [
  '# Map transitions (scripts of the copy)',
  '',
  'Generated by `tools/load-map-calls.ts`, do not edit by hand. On this computer only.',
  '',
  '## Who calls `load_map`',
  '',
  'Map is a file name or a number (in brackets, the map with that number in the original\'s list). Entrance is the second parameter.',
  '',
  '| Script | Procedure | Map | Entrance |',
  '|---|---|---|---|',
  ...calls,
  '',
  '## Map start cell by entrance number',
  '',
  'The map script in `map_enter_p_proc` places the hero by global variable 32 (entrance number): cell = y × 200 + x, elevation, rotation.',
  '',
  '| Map | Map script | Entrance | Cell | Elevation | Rotation |',
  '|---|---|---|---|---|---|',
  ...starts.filter((s) => !s.startsWith('<!--')),
  '',
].join('\n');
fs.mkdirSync('docs/data', { recursive: true });
fs.writeFileSync('docs/data/load-map.md', out);
console.log(`Wrote docs/data/load-map.md: load_map calls ${calls.length}, start cells ${starts.filter((s) => !s.startsWith('<!--')).length}`);
game.close();
