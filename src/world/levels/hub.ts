// The Hub, laid out after the original's maps HUBENT (entrance), HUBDWNTN (downtown), HUBOLDTN (old town), HUBHEIGT (heights) and HUBWATER (water merchants).
// Five maps make one town: downtown in the middle, the entrance to the west, the old town to the north, the heights to the south, the water merchants to the east;
// transitions between them are at the edges, as in the original (letters Y, Z, W, V in the grid lead to another part, X to the wasteland).
// Our cell is a 2×2 square of hexes; walls and houses are where they are in the original. For most maps the playable area is the original's screen
// rectangle (a diamond on the plan): in the original its boundary is held by invisible "blocking" cells; we put stone outside.
// Top view of the original: `node tools/map-view.ts HUBDWNTN 0 12 2 --grid`. File built by `tools/map-to-level.ts`, then edited by hand.
// All critters are peaceful for now (npc) with the original's scripts: their scripts decide who attacks. Weapons in hand follow the original maps' inventory.
// The upper floors of downtown (Decker's lair) and of the old town are separate levels; ladders are exits "on E" both ways.
// Extraction settings for each level: `tools/levels/` (`node tools/levels/check.ts` re-extracts and compares with this file).
