// Necropolis, laid out after the original's maps HOTEL (hotel), HALLDED (Hall of the Dead) and WATRSHD (watershed): each has two floors, an upper one
// (the open-air town, exits to the wasteland are X marks) and a lower one (cellars and tunnels); between them, ladders and crawlways "on E" (exits use:true).
