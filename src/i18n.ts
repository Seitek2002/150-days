export type StringKey = keyof (typeof STRINGS)['ru'];

let current: Lang = 'ru';

export function setLang(lang: Lang): void {
  current = lang;
  document.documentElement.lang = lang;
}

export function getLang(): Lang {
  return current;
}

export function t(key: StringKey): string {
  return STRINGS[current][key];
}

/** Text with substitution: tf('msgHit', { name: 'Rat', dmg: 5 }). */
export function tf(key: StringKey, vars: Record<string, string | number>): string {
  return t(key).replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? ''));
}

/** A fractional number for text: to tenths, in the ru locale — with a decimal comma (1,5 AP). */
export function formatDecimal(n: number): string {
  const text = String(Math.round(n * 10) / 10);
  return current === 'ru' ? text.replace('.', ',') : text;
}

export function detectLang(saved: string): Lang {
  if (saved === 'ru' || saved === 'en') return saved;
  return navigator.language.toLowerCase().startsWith('ru') ? 'ru' : 'en';
}
